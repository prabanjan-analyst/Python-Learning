# Numbers

import math
print(10 + 5)       # Addition
print(10 - 5)       # Subtract
print(10 * 5)       # Multiply
print(10 / 3)       # Divide
print(10 // 3)      # Divide eliminate decimal
print(10 % 3)       # Reminder
print(10 ** 3)      # Exponent

# Arguemented Assignment operator
mark = 10

mark = mark + 5
print(mark)

marks = 10
marks += 3
print(marks)

marks -= 4
marks *= 4
marks /= 4

# Math Methods
print(round(2.3))       # Rounds the lowest int
print(round(2.7))       # Rounds the highest int
print(abs(-3.4))        # Absolute positive number
print(pow(4, 2))        # Power the number(Exponent)

print(math.ceil(2.3))   # Rounds Up
print(math.floor(2.9))  # Rounds Down
print(math.pow(10, 3))  # Power the number(Exponent)
print(math.sqrt(16))    # Taking Squre root
print(math.trunc(4.9))  # Eliminates the decimal
